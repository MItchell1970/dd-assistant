def number(value):
    return value if isinstance(value, int) else 0


def checks():
    """The differences found (an empty list when every copied table adds up and ties to the statements)."""
    by_name = {sheet["sheet"]: sheet for sheet in SHEETS}
    problems = []
    for name, parts, total in SUMS:
        rows = by_name[name]["rows"]
        for column in range(1, len(rows[total])):
            if not isinstance(rows[total][column], int):
                continue
            added = sum(number(rows[i][column]) for i in parts if len(rows[i]) > column)
            if added != rows[total][column]:
                problems.append(f"{name}, column {by_name[name]['header'][column - 1]}: lines add up to {added:,}, "
                                f"printed total {rows[total][column]:,}")
    for name in ACROSS:
        for row in by_name[name]["rows"]:
            if len(row) > 1 and sum(number(v) for v in row[1:-1]) != number(row[-1]):
                problems.append(f"{name}, {row[0]}: segments add up to {sum(number(v) for v in row[1:-1]):,}, "
                                f"printed {number(row[-1]):,}")
    for name, row, column, expected, what in STATEMENTS:
        found = by_name[name]["rows"][row][column]
        if found != expected:
            problems.append(f"{name}: {found} differs from the statements ({what}: {expected:,})")
    for cells, expected in CHARGE:
        added = sum(by_name[name]["rows"][row][column] for name, row, column in cells)
        if added != expected:
            problems.append(f"Depreciation of notes 5, 6 and 7 adds up to {added:,}, statements {expected:,}")
    return problems


def build(path):
    workbook = Workbook()
    index = workbook.active
    index.title = "Index"
    index.append(["Sheet", "Topic", "Note", "Title as printed", "Page", "Unit", "Status"])
    for sheet in SHEETS:
        index.append([sheet["sheet"], sheet["topic"], sheet["note"], sheet["title"],
                      f"note {sheet['note']} (ESEF report, no page)", UNIT, "read"])
        page = workbook.create_sheet(sheet["sheet"])
        page["A1"] = sheet["title"]
        page["A2"] = f"Source: Relatório Anual 2025 (ESEF), nota {sheet['note']}"
        page["A3"] = UNIT
        for column, text in enumerate(["Item"] + sheet["header"], start=1):
            page.cell(row=5, column=column, value=text)
        for line, row in enumerate(sheet["rows"], start=6):
            for column, value in enumerate(row, start=1):
                if value is not None and value != "":
                    page.cell(row=line, column=column, value=value)
        page.column_dimensions["A"].width = 60
    for topic in TOPICS:
        if not any(sheet["topic"] == topic for sheet in SHEETS):
            index.append([None, topic, None, None, None, None, "not read: not disclosed"])
    path.parent.mkdir(parents=True, exist_ok=True)
    workbook.save(path)


