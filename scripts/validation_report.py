"""Write docs/VALIDATION.md: the findings on the real published accounts, classified, with the counts.

Run from the project folder:  python scripts\\validation_report.py
The classification lives in tests/real_findings.py; the findings are recomputed here from the data files.
"""
from __future__ import annotations

import sys
from datetime import date
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from dd_assistant.extract import extract_excel  # noqa: E402
from dd_assistant.metrics import compute_metrics  # noqa: E402
from dd_assistant.rules import alerts, evaluate  # noqa: E402
from tests.real_findings import FALSE_ALARM, FINDINGS, REVIEW, REVIEWED_BY, TRUE, counts  # noqa: E402


def main() -> None:
    lines = ["# Validation on real published accounts", "",
             f"Generated by `scripts/validation_report.py` on {date.today().isoformat()}. General thresholds (no "
             "sector). Classification proposed by Claude Code from the published figures; "
             + (f"reviewed by {REVIEWED_BY} (declared locally)." if REVIEWED_BY else "**not yet reviewed by a person**."),
             ""]
    c = counts()
    total = sum(c.values())
    lines += ["| Classification | Findings |", "|---|---|"]
    lines += [f"| {k} | {c[k]} |" for k in (TRUE, REVIEW, FALSE_ALARM)] + [f"| total | {total} |", ""]
    for file, expected in FINDINGS.items():
        ext = extract_excel(ROOT / "data" / file, file)
        m = compute_metrics(ext.data)
        fired = {r.rule.id: r for r in alerts(evaluate(ext.data, m))}
        lines += [f"## {ext.company}", "", f"Source: `data/{file}` (sheet 'Source' gives the report and pages).", "",
                  "| Rule | Severity | Years | Classification | Why |", "|---|---|---|---|---|"]
        for rid in sorted(set(fired) | set(expected)):
            kind, why = expected.get(rid, ("not classified", "fires but is not in tests/real_findings.py"))
            r = fired.get(rid)
            lines.append(f"| {rid} | {r.rule.severity if r else '—'} | {r.years_text if r else 'does not fire'} | "
                         f"{kind} | {why} |")
        lines.append("")
    lines += ["Limits: two companies, both Portuguese, both read from Excel copies of the published statements. "
              "A true positive means the figures show what the rule says, not that a deal team would treat it as "
              "an issue. EDP (ESEF FY2025) was checked by hand and is not in this table: its 96 MB package is not "
              "in the project."]
    out = ROOT / "docs" / "VALIDATION.md"
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"{out}: {total} findings — " + ", ".join(f"{k}: {v}" for k, v in c.items()))


if __name__ == "__main__":
    main()
