FMT = "#,##0;(#,##0)"


def _put(ws, rows: list[list], periods: int) -> None:
    """Label in A, then '$' and value columns per period (B/C, D/E…), as the PDF prints them."""
    for r in rows:
        label, sign, values = r[0], (r[1] if len(r) > 1 else None), r[2:]
        cells = [label]
        for v in values or [None] * periods:
            cells += [sign, v]
        ws.append(cells)
        for c in ws[ws.max_row][2::2]:
            if isinstance(c.value, int):
                c.number_format = FMT


