"""The public tool (tool.py, demo mode of app.py), against the acceptance criteria of docs/FASE5_DESIGN.md (section 6):
four views without errors, only the palette's colours, severity as shape and colour, leases grey, a source and a
document on every finding card, the multiple slider, no investment wording, every visible figure in the material,
and the three signature titles generated by the engine."""
import os
import re
import unittest
from functools import lru_cache
from pathlib import Path
from unittest import mock

import tool
from dd_assistant import charts, deal_layer as dl, demo
from dd_assistant.dataroom import files_in, read_data_room
from dd_assistant.memo_check import _check_numbers
from dd_assistant.pipeline import analyse

ROOT = Path(__file__).resolve().parents[1]
PALETTE = {charts.BG, charts.CARD, charts.TEXT, charts.MUTED, charts.LINE, charts.RED, charts.GREEN, charts.GREY}
BANNED = re.compile(r"\bno-go\b|\bgo\b|\brecommend\b|should buy", re.I)


_ENV = mock.patch.dict(os.environ, {"DD_DEMO": "1"})


def setUpModule():
    _ENV.start()        # every run and rerun of the app in this file is the public tool


def tearDownModule():
    _ENV.stop()


def fresh(slug: str, view: str = "Summary", multiple: float | None = None):
    from streamlit.testing.v1 import AppTest
    at = AppTest.from_file(str(ROOT / "app.py"), default_timeout=180)
    at.query_params["company"] = slug
    at.run()
    if view != "Summary":
        at.session_state["view"] = view
        at.run()
    if multiple is not None:
        at.slider(key="multiple").set_value(multiple).run()
    return at


@lru_cache(maxsize=None)
def run(slug: str, view: str = "Summary", multiple: float | None = None):
    """A rendered view, shared by the tests that only read it."""
    return fresh(slug, view, multiple)


def text(at) -> str:
    """What a visitor reads: markdown and captions, without tags; ranks and SVG tooltips (data-nocheck, title) out."""
    raw = "\n".join(str(m.value) for m in at.markdown) + "\n" + "\n".join(str(m.value) for m in at.caption)
    raw = re.sub(r"<style>.*?</style>", " ", raw, flags=re.S)
    raw = re.sub(r"<(\w+)[^>]*data-nocheck[^>]*>.*?</\1>", " ", raw, flags=re.S)
    raw = re.sub(r"<title>.*?</title>", " ", raw, flags=re.S)
    return re.sub(r"<[^>]+>", "\n", raw)


class ToolTest(unittest.TestCase):
    def test_views_run_for_every_company(self):
        for c in demo.CASES:
            for view in tool.VIEWS:
                with self.subTest(company=c.slug, view=view):
                    self.assertFalse(run(c.slug, view).exception)

    def test_summary_has_the_band_kpis_chips_and_top_five(self):
        at = run("tap")
        page = "\n".join(str(m.value) for m in at.markdown)
        self.assertIn("Finding intensity, not a recommendation", page)
        self.assertEqual(page.count('class="kpi"'), 4)
        self.assertEqual(len([b for b in at.button if b.key and b.key.startswith("chip-")]), 5)
        self.assertEqual(len([b for b in at.button if b.key and b.key.startswith("top-")]), 5)

    def test_chip_opens_findings_filtered(self):
        at = fresh("tap")
        at = at.button(key="chip-Net debt").click().run()
        self.assertEqual(at.session_state["view"], "Findings")
        self.assertEqual(at.session_state["f_area"], ["Net debt"])

    def test_only_the_palette(self):
        """Criterion 3: every colour in the CSS, the SVG and the theme belongs to the palette."""
        found = set(re.findall(r"#[0-9a-fA-F]{6}", tool.CSS + charts.CSS))
        for view in tool.VIEWS:
            found |= set(re.findall(r"#[0-9a-fA-F]{6}", "\n".join(str(m.value) for m in run("tap", view).markdown)))
        theme = (ROOT / ".streamlit" / "config.toml").read_text(encoding="utf-8")
        found |= set(re.findall(r"#[0-9a-fA-F]{6}", theme))
        self.assertLessEqual({x.lower() for x in found}, PALETTE)

    def test_severity_is_shape_and_colour_and_leases_are_grey(self):
        """Criterion 4."""
        self.assertIn(f'color:{charts.RED}" title="High">▲', tool.sev("High"))
        self.assertIn("●", tool.sev("Medium"))
        self.assertIn("○", tool.sev("Low"))
        b = charts.net_debt(demo.analysis(demo.CASE_BY_SLUG["tap"]))
        self.assertEqual({c.label: c.effect for c in b.columns}["Lease liabilities"], "standard")
        self.assertIn('class="standard"', charts.svg(b, demo.analysis(demo.CASE_BY_SLUG["tap"]).money))

    def test_every_card_has_a_source_and_a_document(self):
        """Criterion 5: each finding card shows where the figure comes from and the document to request."""
        for c in demo.CASES:
            with self.subTest(c.slug):
                page = "\n".join(str(m.value) for m in run(c.slug, "Findings").markdown)
                cards = page.split('<div class="title">')[1:]
                self.assertEqual(len(cards), len(dl.deal_issues(demo.analysis(c))))
                for card in cards:
                    self.assertRegex(card, r"Source:|![A-Z]|p\.\d|note \d")
                    doc = re.search(r"Document to request</div><div>(.*?)</div>", card)
                    self.assertTrue(doc and doc.group(1).strip(), card[:120])

    def test_multiple_moves_only_with_ebitda_adjustments(self):
        """Criterion 6: from 8x to 10x the impact moves on Duriva (EBITDA adjustments), not on TAP; on TAP the
        annotation says the leases are not counted."""
        duriva = analyse(read_data_room(files_in([str(ROOT / "data" / "Duriva_data_room")])), None, "PT")
        self.assertNotEqual(charts.valuation(duriva, 8).columns[-1].value, charts.valuation(duriva, 10).columns[-1].value)
        tap = demo.analysis(demo.CASE_BY_SLUG["tap"])
        self.assertEqual(charts.valuation(tap, 8).columns[-1].value, charts.valuation(tap, 10).columns[-1].value)
        self.assertIn("Not counted: lease liabilities", charts.valuation(tap, 10).annotation)
        at = run("tap", "Impact", 10.0)
        page = "\n".join(str(m.value) for m in at.markdown)
        self.assertIn("At 10x", page)
        self.assertIn("Not counted: lease liabilities", page)

    def test_no_investment_wording(self):
        """Criterion 7."""
        for c in demo.CASES:
            for view in tool.VIEWS:
                with self.subTest(company=c.slug, view=view):
                    self.assertIsNone(BANNED.search(text(run(c.slug, view))))

    def test_every_visible_figure_is_in_the_material(self):
        """Criterion 8: as tests/test_site.py, for every view of the tool."""
        for c in demo.CASES:
            material = demo.material(c)
            for view in tool.VIEWS:
                with self.subTest(company=c.slug, view=view):
                    checked, unmatched, misdated, _ = _check_numbers(text(run(c.slug, view)), material)
                    self.assertGreater(checked, 3)
                    self.assertEqual((unmatched, misdated), ([], []))

    def test_signature_titles_are_generated(self):
        """Section 4 of the design: the three titles come from the engine's figures."""
        a = demo.analysis(demo.CASE_BY_SLUG["tap"])
        self.assertEqual(charts.net_debt(a, company="TAP").title, "Leases, a standard item, explain €2,158m of "
                         "TAP's €2,293m adjusted net debt; diligence adds €177m")
        self.assertTrue(dl.coverage_title(dl.coverage(a)).startswith("22 of 30 rules run on published accounts"))
        r07 = next(d for d in dl.deal_issues(a) if d.key == "R07")
        self.assertEqual(dl.issue_title(r07, a.money), "Receivables grew €63m ahead of revenue: completion accounts, "
                                                       "not price")


if __name__ == "__main__":
    unittest.main()
