"""The ledger of a messy data room (FICTITIOUS, synthetic test data): formats, renamed account, missing month.

The data room is data/Duriva_messy_data_room, generated by scripts/duriva_messy.py from Duriva's annual accounts.
"""
import unittest
from datetime import datetime
from pathlib import Path

from dd_assistant.ledger import month_of, number, read_export, read_ledger

ROOM = Path(__file__).resolve().parents[1] / "data" / "Duriva_messy_data_room"


def room_files(root: Path = ROOM) -> list[tuple[str, bytes]]:
    return [(p.relative_to(root).as_posix(), p.read_bytes()) for p in sorted(root.rglob("*")) if p.is_file()]


class FormatsTest(unittest.TestCase):
    def test_numbers(self):
        for text, value in (("1.234,56", 1234.56), ("-1.234,56", -1234.56), ("(1,234.56)", -1234.56),
                            ("1,234.56", 1234.56), ("844.192,00", 844192.0), ("1234", 1234.0), (-5.5, -5.5),
                            ("", None)):
            with self.subTest(text=text):
                self.assertEqual(number(text), value)

    def test_months(self):
        for text, ym in (("Período: 31.01.2023", (2023, 1)), ("jan-24", (2024, 1)), ("set-25", (2025, 9)),
                         ("Data: 2025-03-31", (2025, 3)), (datetime(2025, 12, 31), (2025, 12))):
            with self.subTest(text=text):
                self.assertEqual(month_of(text), ym)

    def read(self, name):
        return read_export(name, (ROOM / name).read_bytes())

    def test_csv_semicolon_decimal_comma_title_above_the_header(self):
        e = self.read("ERP - exportações mensais/balancete_jan23.csv")
        self.assertEqual(e.month, (2023, 1))
        self.assertEqual(e.lines[0][:4], ("REV100", "Vendas merc. nac.", -844192.0, -844192.0))
        self.assertIn("CSV (';'", e.how)

    def test_csv_comma_brackets_period_column_windows_encoding(self):
        e = self.read("ERP - exportações mensais/ERP_TB_202407.csv")
        self.assertEqual(e.month, (2024, 7))
        self.assertEqual(e.lines[0][:4], ("REV100", "Vendas merc. nac.", -1008616.0, -6975248.0))
        self.assertIn("cp1252", e.how)

    def test_excel_header_on_row_five_with_misnamed_columns(self):
        e = self.read("ERP - exportações mensais/Balancete 2025-03.xlsx")
        self.assertEqual(e.month, (2025, 3))
        self.assertEqual([str(c) for c in e.cols], ["Saldo", "Movimento"])


class LedgerTest(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.L = read_ledger(room_files())

    def test_thirty_six_months_one_series_per_account(self):
        self.assertEqual(len(self.L.months), 36)
        self.assertEqual((self.L.months[0], self.L.months[-1]), ((2023, 1), (2025, 12)))
        self.assertEqual(len(self.L.series), 36)
        self.assertTrue(all(len(s.points) == 36 for s in self.L.series))

    def test_swapped_columns_are_read_by_content(self):
        s = self.L.by_code("REV100")
        p = s.points[(2025, 3)]
        self.assertEqual((p.movement, p.closing), (-1127780.0, -3117980.0))   # 'Saldo' held the movement
        self.assertTrue(any("wrong way round" in n for n in self.L.notes))

    def test_renamed_account_is_one_series(self):
        s = self.L.by_code("4121")
        self.assertIs(s, self.L.by_code("4120"))
        self.assertEqual(s.codes, ["4120", "4121"])
        july, june = s.points[(2024, 7)], s.points[(2024, 6)]
        self.assertAlmostEqual(july.closing - july.movement, june.closing, places=2)

    def test_missing_month_is_rebuilt_and_marked(self):
        for s in self.L.series:
            aug, sep = s.points[(2024, 8)], s.points[(2024, 9)]
            with self.subTest(account=s.code):
                self.assertIn("no export for 2024-08", aug.derived)
                self.assertAlmostEqual(aug.closing, sep.closing - sep.movement, places=2)
        self.assertTrue(any("No export for 2024-08" in n for n in self.L.notes))

    def test_trial_balances_tie_to_december(self):
        ties = [n for n in self.L.notes if n.startswith("Trial balance")]
        self.assertEqual(ties, [f"Trial balance {y}: 36 of 36 accounts equal the December export." for y in
                                (2023, 2024, 2025)])

    def test_every_figure_keeps_its_file_and_row(self):
        p = self.L.by_code("221100").points[(2025, 12)]
        self.assertEqual(p.source, "ERP - exportações mensais/Balancete 2025-12.xlsx › row 37")


if __name__ == "__main__":
    unittest.main()
